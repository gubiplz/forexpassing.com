// Stamps the canonical footer (bin/footer.html) into every static page.
//
//   node bin/inject-footer.mjs
//
// The React pages get their footer from <SiteFooter /> in src/pages/shared.tsx;
// the plain HTML pages in public/ cannot import anything, so they carry a copy
// between FOOTER:START / FOOTER:END markers and this script keeps those copies
// identical. Run it after editing bin/footer.html and commit the result — the
// build stays offline and the served files stay plain static HTML.
//
// Idempotent: it replaces whatever sits between the markers, so running it
// twice changes nothing. A page without markers is reported and skipped rather
// than guessed at.

import { readFile, writeFile } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const PUBLIC = join(ROOT, 'public');

const START = '<!-- FOOTER:START -->';
const END = '<!-- FOOTER:END -->';

// Pages that carry the centred footer. safe.html is deliberately absent: it
// mirrors SafePage, which uses the three-column variant instead.
const PAGES = [
  'about-us.html',
  'watch.html',
  'thank-you.html',
  'welcome.html',
  '404.html',
  'terms.html',
  'privacy.html',
];

const footer = (await readFile(join(ROOT, 'bin', 'footer.html'), 'utf8')).trim();
const block = `${START}\n<!-- generated by bin/inject-footer.mjs from bin/footer.html — edit that file, not this -->\n${footer}\n${END}`;

let written = 0;
for (const page of PAGES) {
  const path = join(PUBLIC, page);
  const html = await readFile(path, 'utf8');
  const from = html.indexOf(START);
  const to = html.indexOf(END);
  if (from === -1 || to === -1 || to < from) {
    console.error(`[inject-footer] ${page}: FOOTER:START/END markers missing — skipped`);
    continue;
  }
  const next = html.slice(0, from) + block + html.slice(to + END.length);
  if (next !== html) {
    await writeFile(path, next);
    written++;
  }
}

console.log(`[inject-footer] ${written} of ${PAGES.length} pages updated`);
